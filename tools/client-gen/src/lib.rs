//! Generates `calimero-client`'s route layer (`crates/client/src/generated/`)
//! from the node's OpenAPI document (`docs/public/openapi.json`), the way
//! mero-js (`scripts/gen-methods.mjs`), calimero-client-py
//! (`scripts/generate_openapi_client.py`) and the Kotlin SDK
//! (`codegen/facade.py`) generate theirs: one method per operation, grouped by
//! `x-calimero-group`, with the same names in snake case.
//!
//! - `types.rs`: the components and the operations' inline bodies and answers
//!   as Rust types ([`types`]);
//! - `routes.rs`: one async method per operation on its group's accessor
//!   (`client.orgs()`), sending through the client's `Transport` ([`routes`]).
//!
//! The output is formatted with `rustfmt` (the repository's `rustfmt.toml`)
//! and checked in, so building the client needs no generator. Its test
//! regenerates into a temporary directory and fails while the checked-in code
//! differs: a change to a route regenerates the document
//! (`UPDATE_OPENAPI=1 cargo test -p calimero-node --lib openapi`) and then this
//! (`cargo run -p calimero-client-gen`), in the same change.

use std::io::Write as _;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

use eyre::{bail, eyre, Result as EyreResult, WrapErr};
use serde_json::Value;

mod naming;
mod routes;
mod types;

use types::Types;

/// The repository's root, from this crate's directory.
#[must_use]
pub fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// The document the client is generated from.
#[must_use]
pub fn document_path(root: &Path) -> PathBuf {
    root.join("docs/public/openapi.json")
}

/// Where the generated files are checked in.
#[must_use]
pub fn output_dir(root: &Path) -> PathBuf {
    root.join("crates/client/src/generated")
}

/// What one run generated.
pub struct Generated {
    /// `(file name, contents)`, formatted.
    pub files: Vec<(&'static str, String)>,
    pub methods: usize,
    /// The operations left out: their answers are event streams.
    pub streams: Vec<String>,
}

/// Generate the route layer from `doc`, formatted with the `rustfmt.toml` in `root`.
///
/// # Errors
/// When the document has a shape this generator does not turn into Rust, or
/// `rustfmt` fails.
pub fn generate(doc: &Value, root: &Path) -> EyreResult<Generated> {
    let mut types = Types::new(doc)?;
    let (routes_body, methods, streams) = routes::emit(doc, &mut types)?;
    let types_rs = types.emit();
    let mut routes_rs = String::from(
        "//! The node API's operations, generated by `calimero-client-gen` from\n\
         //! `docs/public/openapi.json`: do not edit. `cargo run -p calimero-client-gen`\n\
         //! regenerates them; its test fails while they differ from the document.\n\
         //!\n\
         //! One method per operation on the group `x-calimero-group` names\n\
         //! (`client.orgs().invite_create(..)`), named as the other Calimero SDKs name\n\
         //! it. Each sends through [`Client::transport`] and answers the operation's\n\
         //! typed success answer, a refusal as [`crate::Error`]. Event streams are\n\
         //! not here: [`Client::events`] and [`Client::presence_stream`] read them.\n",
    );
    if !streams.is_empty() {
        routes_rs.push_str(&format!("//! Left out: {}.\n", streams.join(", ")));
    }
    if types::uses_word(&routes_body, "BTreeMap") {
        routes_rs.push_str("\nuse std::collections::BTreeMap;\n");
    }
    routes_rs.push_str("\nuse reqwest::Method;\n");
    let json: Vec<&str> = ["Map", "Value"]
        .into_iter()
        .filter(|t| types::uses_word(&routes_body, t))
        .collect();
    if !json.is_empty() {
        routes_rs.push_str(&format!("use serde_json::{{{}}};\n", json.join(", ")));
    }
    routes_rs.push_str(
        "\n#[allow(clippy::wildcard_imports, reason = \"every generated type may be named\")]\n\
         use super::types::*;\n",
    );
    let mut own = vec!["Client", "Request", "Result"];
    if types::uses_word(&routes_body, "Passkey") {
        own.insert(1, "Passkey");
    }
    routes_rs.push_str(&format!("use crate::{{{}}};\n", own.join(", ")));
    if types::uses_word(&routes_body, "OperatorSigner") {
        routes_rs.push_str("use crate::route::{self, OperatorSigner};\n\n");
    } else {
        routes_rs.push_str("use crate::route;\n\n");
    }
    routes_rs.push_str(&routes_body);
    Ok(Generated {
        files: vec![
            ("routes.rs", rustfmt(&routes_rs, root)?),
            ("types.rs", rustfmt(&types_rs, root)?),
        ],
        methods,
        streams,
    })
}

/// `code` as `cargo fmt` writes it in this workspace (edition 2021, `rustfmt.toml`).
fn rustfmt(code: &str, root: &Path) -> EyreResult<String> {
    let rustfmt = std::env::var_os("RUSTFMT").unwrap_or_else(|| "rustfmt".into());
    let mut child = Command::new(rustfmt)
        .args(["--edition", "2021", "--emit", "stdout", "--config-path"])
        .arg(root.join("rustfmt.toml"))
        .current_dir(root)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .wrap_err("running rustfmt")?;
    child
        .stdin
        .take()
        .ok_or_else(|| eyre!("rustfmt has no stdin"))?
        .write_all(code.as_bytes())?;
    let out = child.wait_with_output()?;
    if !out.status.success() {
        bail!(
            "rustfmt refused the generated code: {}",
            String::from_utf8_lossy(&out.stderr)
        );
    }
    Ok(String::from_utf8(out.stdout)?)
}

/// Read the document at `root` and generate from it.
///
/// # Errors
/// As [`generate`], and when the document cannot be read.
pub fn generate_at(root: &Path) -> EyreResult<Generated> {
    let path = document_path(root);
    let doc: Value = serde_json::from_str(
        &std::fs::read_to_string(&path).wrap_err_with(|| format!("{}", path.display()))?,
    )?;
    generate(&doc, root)
}

/// Write `generated`'s files into `dir`.
///
/// # Errors
/// When a file cannot be written.
pub fn write(generated: &Generated, dir: &Path) -> EyreResult<()> {
    std::fs::create_dir_all(dir)?;
    for (name, code) in &generated.files {
        std::fs::write(dir.join(name), code).wrap_err_with(|| (*name).to_owned())?;
    }
    Ok(())
}

/// The files of `fresh` that differ from (or are missing in) `checked_in`.
#[must_use]
pub fn differing(fresh: &Path, checked_in: &Path, names: &[&str]) -> Vec<String> {
    names
        .iter()
        .filter(|n| std::fs::read(fresh.join(n)).ok() != std::fs::read(checked_in.join(n)).ok())
        .map(|n| (*n).to_owned())
        .collect()
}

#[cfg(test)]
mod tests {
    use super::{differing, generate_at, output_dir, repo_root, write};

    /// The checked-in route layer is the one the committed document generates.
    #[test]
    fn the_checked_in_client_is_what_the_document_generates() {
        let root = repo_root();
        let generated = generate_at(&root).expect("generate the client");
        let fresh = tempfile::tempdir().expect("a temporary directory");
        write(&generated, fresh.path()).expect("write the client");
        let names: Vec<&str> = generated.files.iter().map(|(n, _)| *n).collect();
        let stale = differing(fresh.path(), &output_dir(&root), &names);
        assert!(
            stale.is_empty(),
            "crates/client/src/generated/{{{}}} is not what docs/public/openapi.json generates: \
             run `cargo run -p calimero-client-gen` and commit the result",
            stale.join(",")
        );
    }
}
