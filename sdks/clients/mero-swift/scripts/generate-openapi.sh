#!/usr/bin/env bash
# MeroAPI: the Swift client generated from core's OpenAPI document.
#
#   scripts/generate-openapi.sh          regenerate Sources/MeroAPI/Generated and the facade
#   scripts/generate-openapi.sh check    exit 1 if the checked-in sources differ from a fresh generation
#
# The document is core's docs/public/openapi.json, read from the core checkout
# this SDK sits in (sdks/clients/mero-swift, so ../../../docs/public/openapi.json;
# MERO_OPENAPI_SPEC names another file). Nothing is fetched for it. The
# read-only SwiftPM mirror (calimero-network/swift-sdk) carries the generated
# output, not the document, so building MeroKit never needs it.
#
# scripts/openapi-normalize.py rewrites a copy into the dialect the generator
# reads, swift-openapi-generator (openapi/generator's GENERATOR_VERSION, built
# once into $MERO_OPENAPI_CACHE) writes Types.swift and Client.swift, and this
# script stamps them; scripts/generate-facade.py then writes MeroKit's facade
# over them (Sources/MeroKit/Api/Generated/Facade.swift: `client.orgs.get(org:)`,
# ...). The output is checked in so that building MeroKit never runs the
# generator or needs its plugin. In core, `python3 scripts/sdks.py generate
# mero-swift` runs this, and the `SDK codegen drift` job compares the result.
#
# GENERATOR=/path/to/swift-openapi-generator skips building it (it must be
# GENERATOR_VERSION). Needs python3 and a Swift toolchain (macOS or Linux), and
# git with network access the first time, to build the generator.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SPEC="${MERO_OPENAPI_SPEC:-$ROOT/../../../docs/public/openapi.json}"
CONFIG="$ROOT/openapi/openapi-generator-config.yaml"
OUT="$ROOT/Sources/MeroAPI/Generated"
FACADE="$ROOT/Sources/MeroKit/Api/Generated/Facade.swift"
# shellcheck source=/dev/null
. "$ROOT/openapi/generator"
CACHE="${MERO_OPENAPI_CACHE:-$ROOT/.build/openapi-generator}"

die() { echo "generate-openapi: $*" >&2; exit 1; }

[ -f "$SPEC" ] || die "no OpenAPI document at $SPEC: run this inside calimero-network/core (sdks/clients/mero-swift), or set MERO_OPENAPI_SPEC"

# The generator at GENERATOR_VERSION, built from source on first use.
generator() {
  if [ -n "${GENERATOR:-}" ]; then echo "$GENERATOR"; return; fi
  local src="$CACHE/swift-openapi-generator-$GENERATOR_VERSION"
  local bin="$src/.build/release/swift-openapi-generator"
  if [ ! -x "$bin" ]; then
    rm -rf "$src"
    mkdir -p "$CACHE"
    git clone --quiet --depth 1 --branch "$GENERATOR_VERSION" \
      https://github.com/apple/swift-openapi-generator "$src" >&2
    (cd "$src" && swift build -c release --product swift-openapi-generator >&2)
  fi
  echo "$bin"
}

# Generate into directory $1 (Types.swift, Client.swift) and file $2 (the facade).
generate_into() {
  local dest="$1" facade="$2" work
  work="$(mktemp -d)"
  trap 'rm -rf "$work"' RETURN
  python3 "$ROOT/scripts/openapi-normalize.py" "$SPEC" "$work/openapi.json"
  "$(generator)" generate "$work/openapi.json" --config "$CONFIG" --output-directory "$work/out" >"$work/log" 2>&1 \
    || { cat "$work/log" >&2; die "the generator failed"; }
  # A warning means a schema was skipped, and with it a property: fail rather than ship the gap.
  if grep -iE '(warning|error):' "$work/log" >&2; then die "the generator warned (above); fix the normalization"; fi
  mkdir -p "$dest"
  for file in Types.swift Client.swift; do
    {
      echo "// swift-format-ignore-file"
      echo "// swiftlint:disable all"
      echo "// Generated by scripts/generate-openapi.sh (swift-openapi-generator $GENERATOR_VERSION) from"
      echo "// core's docs/public/openapi.json. Do not edit."
      cat "$work/out/$file"
    } >"$dest/$file"
  done
  mkdir -p "$(dirname "$facade")"
  python3 "$ROOT/scripts/generate-facade.py" "$SPEC" "$dest/Types.swift" "$facade"
}

case "${1:-generate}" in
  generate)
    generate_into "$OUT" "$FACADE"
    echo "wrote ${OUT#"$ROOT"/} and ${FACADE#"$ROOT"/}"
    ;;
  check)
    fresh="$(mktemp -d)"
    trap 'rm -rf "$fresh"' EXIT
    generate_into "$fresh/MeroAPI" "$fresh/Facade.swift"
    stale=0
    diff -ru "$OUT" "$fresh/MeroAPI" >&2 || stale=1
    diff -u "$FACADE" "$fresh/Facade.swift" >&2 || stale=1
    [ "$stale" = 0 ] || die "the generated sources are stale: run scripts/generate-openapi.sh and commit the result"
    echo "Sources/MeroAPI/Generated and the facade match docs/public/openapi.json"
    ;;
  *)
    sed -n '2,24p' "$0" >&2
    exit 2
    ;;
esac
