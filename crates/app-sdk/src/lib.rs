//! The Rust app SDK for `calimero:app`: the `app` attributes, the shared storage encoding,
//! tables with indexes, collections, `env` and guards. Apps compile it into their
//! `wasm32-wasip2` component.

#[cfg(target_arch = "wasm32")]
#[allow(
    clippy::all,
    clippy::pedantic,
    unused,
    missing_docs,
    unsafe_op_in_unsafe_fn,
    reason = "generated by wit-bindgen"
)]
#[doc(hidden)]
pub mod bindings;

pub mod action;
pub mod app;
pub mod blob;
pub mod collections;
mod commons;
pub mod encoding;
pub mod env;
pub mod error;
pub mod guards;
pub mod json;
pub mod search;
pub mod store;
pub mod table;

#[cfg(all(feature = "testing", not(target_arch = "wasm32")))]
pub mod testing;

#[doc(hidden)]
#[path = "private.rs"]
pub mod __private;

pub use action::{ActionCtx, Request, Response};
pub use blob::{BlobInfo, BlobRef};
pub use collections::{
    CborSha256, Cell, ContentHash, Counter, Frozen, Mark, PerUser, RichText, Set, Span, Text,
    UnorderedMap, Vector,
};
pub use encoding::key::{FromKey, FromKeyPart, KeyPart, ToKey, ToKeyPart};
