//! Typed clients for an app, from its ABI: a thin layer over the clients that already speak
//! the sealed channel (mero-js's `CalimeroClient`, calimero-client-py's `Client`), one method
//! per app method sending their `client.apps.call` (through the app's log) or
//! `client.apps.view`. No new runtime: the types are the ABI's, mapped as [`crate::openapi`]
//! maps them, and the transport is the client's.

use crate::abi::AppAbi;
use crate::openapi::pascal;

mod python;
mod typescript;

/// What a client is generated for.
#[derive(Clone, Debug)]
pub struct Target<'a> {
    /// The app's name; the client class is its PascalCase plus `Client`.
    pub name: &'a str,
}

impl Target<'_> {
    fn class(&self) -> String {
        let base = pascal(self.name);
        if base.is_empty() {
            return "AppClient".to_owned();
        }
        format!("{base}Client")
    }
}

/// A TypeScript module over mero-js.
#[must_use]
pub fn typescript(abi: &AppAbi, target: &Target<'_>) -> String {
    typescript::module(abi, &target.class())
}

/// A Python module over calimero-client-py.
#[must_use]
pub fn python(abi: &AppAbi, target: &Target<'_>) -> String {
    python::module(abi, &target.class())
}

/// The header line naming where a generated file came from.
fn provenance(abi: &AppAbi) -> String {
    format!(
        "Generated by `mero-app-build codegen` from the app's ABI (abiVersion {}{}). Do not edit.",
        abi.abi_version,
        abi.world
            .as_deref()
            .map(|w| format!(", {w}"))
            .unwrap_or_default()
    )
}
