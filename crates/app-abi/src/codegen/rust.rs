//! The Rust clients an app calls the apps it `uses` through: for each reference, a module with
//! the target's types and error enum and a `Client` whose methods are the target's methods an
//! app may call, over the SDK's cross-app calls (`env::xcall_call`, `env::xcall_view`,
//! `env::xcall`). `calimero-app-build`'s `uses` writes it from the app's `calimero.lock` and
//! vendored ABIs, for the app's `build.rs`.
//!
//! The JSON is the SDK's (D20): `u64`/`i64` as decimal strings and `bytes` as base64url at the
//! top level of an argument, a result or a field, through `calimero_sdk::json`'s `with`
//! modules; nested inside another type they have no JSON form, and generation fails.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

use eyre::{bail, Result as EyreResult};

use crate::abi::{AppAbi, EnumRepr, Field, Kind, Method, Shape, TypeDef, VariantData};
use crate::openapi::pascal;
use crate::ty::{Int, Type};

use super::ident::{sanitize, Scope};

const SDK: &str = "::calimero_sdk";
const SERDE: &str = "::calimero_sdk::__private::serde";
const JSON: &str = "::calimero_sdk::__private::serde_json";
const VALUE: &str = "::calimero_sdk::__private::serde_json::Value";

/// The names a reference's module declares itself, and the prelude names generated code
/// spells bare; an app type with one of these names is renamed (`Error` → `Error_`).
const RESERVED: &[&str] = &[
    "Box", "Client", "Error", "Option", "Result", "Sender", "String", "Vec", "__Wire",
];

/// One reference of an app, as `[package.metadata.calimero.uses]` declares it and
/// `calimero.lock` pins it.
#[derive(Clone, Copy, Debug)]
pub struct Use<'a> {
    /// The name the app knows it by, and `env::linked` reads it under.
    pub name: &'a str,
    pub package: &'a str,
    /// The release the lock pins, whose ABI was vendored.
    pub version: &'a str,
    pub range: &'a str,
    /// `create` or `attach`.
    pub mode: &'a str,
    /// The methods the app calls as the person it serves; when any are listed, the client has
    /// only those.
    pub methods: &'a [String],
}

/// Whether the client has `method`: a call or a view another app may call (`allowApps`), with
/// no passkey step (`confirm`), and one of the reference's `methods` when it lists any.
#[must_use]
pub fn callable(reference: &Use<'_>, name: &str, method: &Method) -> bool {
    method.client_callable()
        && !method.confirm
        && !method.allow_apps.is_empty()
        && (reference.methods.is_empty() || reference.methods.iter().any(|m| m == name))
}

/// The `uses` module for these references: `pub mod uses { pub mod <name> { .. } pub fn
/// <name>() .. }`, which the app includes from `build.rs`'s output.
pub fn uses_module(refs: &[(Use<'_>, &AppAbi)]) -> EyreResult<String> {
    let mut s = String::new();
    s.push_str(
        "// Generated by calimero-app-build (`calimero_app_build::uses`) from calimero.lock and\n\
         // calimero/abi. Do not edit: `meroctl app uses update` changes what it is made from.\n\n",
    );
    s.push_str(
        "/// The apps this app's release `uses`, each with a typed client from its vendored ABI.\n\
         #[allow(\n    dead_code,\n    missing_docs,\n    non_camel_case_types,\n    non_snake_case,\n    \
         unused_imports,\n    clippy::all,\n    clippy::pedantic,\n    clippy::nursery\n)]\npub mod uses {\n",
    );
    for (reference, abi) in refs {
        if !is_reference_name(reference.name) {
            bail!(
                "uses.{}: a reference's name is a-z, 0-9 and _, starting with a letter",
                reference.name
            );
        }
        s.push_str(&Module::new(abi, reference)?.write()?);
        let _ = write!(
            s,
            "\n/// The `{name}` app this instance is linked to (`env::linked(\"{name}\")`), or\n\
             /// `NotLinked {{ name }}` when nothing is linked under `{name}`.\n\
             pub fn {name}() -> ::core::result::Result<{name}::Client, {SDK}::AppError> {{\n    \
             {name}::Client::linked().ok_or_else(|| {{\n        \
             {SDK}::AppError::with_fields(\"NotLinked\", {JSON}::json!({{ \"name\": {name}::NAME }}))\n    \
             }})\n}}\n",
            name = reference.name,
        );
    }
    s.push_str("}\n");
    Ok(s)
}

fn is_reference_name(name: &str) -> bool {
    name.starts_with(|c: char| c.is_ascii_lowercase())
        && name
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
        && !is_keyword(name)
}

/// One reference's module.
struct Module<'a> {
    abi: &'a AppAbi,
    reference: &'a Use<'a>,
    scope: Scope,
    /// Each described type's Rust name, by its entry name.
    names: BTreeMap<String, String>,
    /// Types the ABI names but does not describe, declared as JSON values: Rust name by ABI
    /// name.
    opaque: BTreeMap<String, String>,
    /// The generic parameters in scope, inside a generic type's declaration.
    params: Vec<String>,
    /// The type being declared, whose fields box what holds it again.
    current: Option<String>,
}

impl<'a> Module<'a> {
    fn new(abi: &'a AppAbi, reference: &'a Use<'a>) -> EyreResult<Self> {
        let mut scope = Scope::new(RESERVED);
        let names = abi
            .types
            .keys()
            .map(|name| (name.clone(), scope.take(sanitize(name))))
            .collect();
        Ok(Self {
            abi,
            reference,
            scope,
            names,
            opaque: BTreeMap::new(),
            params: Vec::new(),
            current: None,
        })
    }

    fn write(mut self) -> EyreResult<String> {
        let r = self.reference;
        let lifecycle = if r.mode == "attach" {
            format!(
                "attached by the owner: an instance with its own lifecycle, which may run any release in `{}`",
                r.range
            )
        } else {
            "created with this instance and upgraded with it, within the range".to_owned()
        };
        let mut body = String::new();
        let _ = writeln!(
            body,
            "\n/// `{}` {} (`{}`, `{}`): {lifecycle}. From its vendored ABI.",
            r.package, r.version, r.range, r.mode
        );
        let _ = writeln!(body, "pub mod {} {{", r.name);
        let _ = writeln!(
            body,
            "    /// The reference's name, as `env::linked` reads it.\n    pub const NAME: &str = {:?};\n    \
             /// The package it names.\n    pub const PACKAGE: &str = {:?};\n    \
             /// The release whose ABI this client was generated from.\n    pub const VERSION: &str = {:?};",
            r.name, r.package, r.version
        );
        // Types first: their names are needed by the methods and errors, which may also
        // meet types the ABI does not describe (declared at the end).
        let types: Vec<(String, TypeDef)> = self
            .abi
            .types
            .iter()
            .map(|(n, d)| (n.clone(), d.clone()))
            .collect();
        for (name, def) in &types {
            body.push_str(&self.declare(name, def)?);
        }
        body.push_str(&self.errors()?);
        body.push_str(&self.client()?);
        for (abi_name, rust) in &self.opaque {
            let _ = writeln!(
                body,
                "\n    /// `{abi_name}`: the ABI names it without describing its shape, so it is its JSON.\n    \
                 pub type {rust} = {VALUE};"
            );
        }
        body.push_str("}\n");
        Ok(body)
    }

    // ── types ──────────────────────────────────────────────────────────────────────────────

    /// The Rust spelling of `ty`. `nested`: inside another type, where `u64`, `i64` and
    /// `bytes` have no JSON form (D20).
    fn ty(&mut self, ty: &Type, nested: bool) -> EyreResult<String> {
        Ok(match ty {
            Type::Unit => "()".to_owned(),
            Type::Bool => "bool".to_owned(),
            Type::Int(int) => {
                if nested && int.is_string() {
                    bail!("{ty} inside another type has no JSON form (D20)");
                }
                match int {
                    Int::U64Number => "u64".to_owned(),
                    Int::I64Number => "i64".to_owned(),
                    other => other.name().to_owned(),
                }
            }
            Type::Float(false) => "f32".to_owned(),
            Type::Float(true) => "f64".to_owned(),
            Type::Char => "char".to_owned(),
            Type::String => "String".to_owned(),
            Type::Bytes => {
                if nested {
                    bail!("bytes inside another type has no JSON form (D20)");
                }
                "Vec<u8>".to_owned()
            }
            Type::Option(inner) => {
                let inner_nested = nested || !is_d20(inner);
                format!("Option<{}>", self.ty(inner, inner_nested)?)
            }
            Type::List(inner) => format!("Vec<{}>", self.ty(inner, true)?),
            Type::Set(inner) => {
                format!("::std::collections::BTreeSet<{}>", self.ty(inner, true)?)
            }
            Type::Tuple(items) => {
                let items = items
                    .iter()
                    .map(|t| self.ty(t, true))
                    .collect::<EyreResult<Vec<_>>>()?;
                if items.len() == 1 {
                    format!("({},)", items[0])
                } else {
                    format!("({})", items.join(", "))
                }
            }
            Type::Array(inner, n) => format!("[{}; {n}]", self.ty(inner, true)?),
            Type::Map(k, v) => format!(
                "::std::collections::BTreeMap<{}, {}>",
                self.ty(k, true)?,
                self.ty(v, true)?
            ),
            Type::Named(text) => self.named(text, ty)?,
        })
    }

    fn named(&mut self, text: &str, ty: &Type) -> EyreResult<String> {
        if self.params.iter().any(|p| p == text) {
            return Ok(text.to_owned());
        }
        if let Some((name, _, args)) = self.abi.shape_of(ty) {
            let rust = self.names[&name].clone();
            if args.is_empty() {
                return Ok(rust);
            }
            let args = args
                .iter()
                .map(|a| self.ty(a, true))
                .collect::<EyreResult<Vec<_>>>()?;
            return Ok(format!("{rust}<{}>", args.join(", ")));
        }
        match ty.named_parts() {
            Some((name, args)) if args.is_empty() => {
                if let Some(rust) = self.opaque.get(&name) {
                    return Ok(rust.clone());
                }
                let rust = self.scope.take(sanitize(&name));
                let _ = self.opaque.insert(name, rust.clone());
                Ok(rust)
            }
            _ => Ok(VALUE.to_owned()),
        }
    }

    /// A field's type: `ty`, boxed where it holds the type being declared again.
    fn field_ty(&mut self, ty: &Type) -> EyreResult<String> {
        let rust = self.ty(ty, false)?;
        let holds_current = |m: &Self, t: &Type| {
            m.current
                .as_ref()
                .is_some_and(|current| m.reaches(t, current, &mut BTreeSet::new()))
        };
        Ok(match ty {
            Type::Option(inner) if holds_current(self, inner) => {
                format!("Option<Box<{}>>", self.ty(inner, true)?)
            }
            Type::Named(_) if holds_current(self, ty) => format!("Box<{rust}>"),
            _ => rust,
        })
    }

    /// Whether a value of `ty` holds a `target` inline (not behind a list, set or map), which
    /// Rust needs boxed.
    fn reaches(&self, ty: &Type, target: &str, seen: &mut BTreeSet<String>) -> bool {
        match ty {
            Type::Option(inner) | Type::Array(inner, _) => self.reaches(inner, target, seen),
            Type::Tuple(items) => items.iter().any(|t| self.reaches(t, target, seen)),
            Type::Named(_) => {
                let Some((name, def, _)) = self.abi.shape_of(ty) else {
                    return false;
                };
                if name == target {
                    return true;
                }
                if !seen.insert(name) {
                    return false;
                }
                inline_types(&def.shape)
                    .iter()
                    .any(|t| self.reaches(t, target, seen))
            }
            _ => false,
        }
    }

    fn declare(&mut self, abi_name: &str, def: &TypeDef) -> EyreResult<String> {
        let rust = self.names[abi_name].clone();
        self.params.clone_from(&def.params);
        self.current = Some(abi_name.to_owned());
        let generics = if def.params.is_empty() {
            String::new()
        } else {
            format!("<{}>", def.params.join(", "))
        };
        let mut s = String::new();
        let _ = writeln!(
            s,
            "\n    /// `{abi_name}`, as the app's JSON carries it.\n    \
             #[derive(Clone, Debug, PartialEq, {SERDE}::Serialize, {SERDE}::Deserialize)]"
        );
        match &def.shape {
            Shape::Record(fields) => {
                let _ = writeln!(s, "    #[serde(crate = \"{SERDE}\")]");
                let _ = writeln!(s, "    pub struct {rust}{generics} {{");
                s.push_str(&self.fields(fields, "        ", "pub ")?);
                s.push_str("    }\n");
            }
            Shape::Newtype(inner) => {
                let _ = writeln!(s, "    #[serde(crate = \"{SERDE}\")]");
                let item = self.item(inner, "pub ")?;
                let _ = writeln!(s, "    pub struct {rust}{generics}({item});");
            }
            Shape::Tuple(items) => {
                let _ = writeln!(s, "    #[serde(crate = \"{SERDE}\")]");
                let items = items
                    .iter()
                    .map(|t| self.item(t, "pub "))
                    .collect::<EyreResult<Vec<_>>>()?;
                let _ = writeln!(s, "    pub struct {rust}{generics}({});", items.join(", "));
            }
            Shape::Unit => {
                let _ = writeln!(s, "    #[serde(crate = \"{SERDE}\")]");
                let _ = writeln!(s, "    pub struct {rust};");
            }
            Shape::Enum { repr, variants } => {
                let repr = match repr {
                    EnumRepr::External => String::new(),
                    EnumRepr::Internal { tag } => format!(", tag = {tag:?}"),
                    EnumRepr::Adjacent { tag, content } => {
                        format!(", tag = {tag:?}, content = {content:?}")
                    }
                    EnumRepr::Untagged => ", untagged".to_owned(),
                };
                let _ = writeln!(s, "    #[serde(crate = \"{SERDE}\"{repr})]");
                let _ = writeln!(s, "    pub enum {rust}{generics} {{");
                let mut variants_scope = Scope::new(&[]);
                for v in variants {
                    let ident = variants_scope.take(sanitize(&pascal(&v.name)));
                    let _ = writeln!(s, "        #[serde(rename = {:?})]", v.name);
                    match &v.data {
                        VariantData::Unit => {
                            let _ = writeln!(s, "        {ident},");
                        }
                        VariantData::Newtype(t) => {
                            let item = self.item(t, "")?;
                            let _ = writeln!(s, "        {ident}({item}),");
                        }
                        VariantData::Tuple(items) => {
                            let items = items
                                .iter()
                                .map(|t| self.item(t, ""))
                                .collect::<EyreResult<Vec<_>>>()?;
                            let _ = writeln!(s, "        {ident}({}),", items.join(", "));
                        }
                        VariantData::Record(fields) => {
                            let _ = writeln!(s, "        {ident} {{");
                            s.push_str(&self.fields(fields, "            ", "")?);
                            s.push_str("        },\n");
                        }
                    }
                }
                s.push_str("    }\n");
            }
        }
        self.params.clear();
        self.current = None;
        Ok(s)
    }

    /// A tuple item or newtype field: its D20 `with`, then its type.
    fn item(&mut self, ty: &Type, vis: &str) -> EyreResult<String> {
        let rust = self.field_ty(ty)?;
        Ok(match d20_module(ty) {
            Some(m) => format!("#[serde(with = \"{SDK}::json::{m}\")] {vis}{rust}"),
            None => format!("{vis}{rust}"),
        })
    }

    fn fields(&mut self, fields: &[Field], indent: &str, vis: &str) -> EyreResult<String> {
        let mut s = String::new();
        let mut scope = Scope::new(&[]);
        for f in fields {
            let ident = scope.take(snake(&f.name));
            // A field the JSON may leave out that is not an `Option` in the app reads as one
            // here, `None` when it is left out.
            let ty = if f.optional && !f.ty.is_optional() {
                Type::Option(Box::new(f.ty.clone()))
            } else {
                f.ty.clone()
            };
            let rust = self.field_ty(&ty)?;
            let mut attrs = vec![format!("rename = {:?}", f.name)];
            if let Some(m) = d20_module(&ty) {
                attrs.push(format!("with = \"{SDK}::json::{m}\""));
            }
            if ty.is_optional() {
                attrs.push("default".to_owned());
                if f.optional {
                    attrs.push("skip_serializing_if = \"Option::is_none\"".to_owned());
                }
            }
            let _ = writeln!(
                s,
                "{indent}#[serde({})]\n{indent}{vis}{ident}: {rust},",
                attrs.join(", ")
            );
        }
        Ok(s)
    }

    // ── errors ─────────────────────────────────────────────────────────────────────────────

    fn errors(&mut self) -> EyreResult<String> {
        let errors = self.abi.errors.clone();
        let mut scope = Scope::new(&["Other"]);
        let mut public = String::new();
        let mut wire = String::new();
        let mut from_wire = String::new();
        let mut to_wire = String::new();
        for (code, fields) in &errors {
            let ident = scope.take(sanitize(code));
            let mut field_scope = Scope::new(&[]);
            let mut idents = Vec::new();
            let mut public_fields = String::new();
            let mut wire_fields = String::new();
            for (name, ty) in fields {
                let field = field_scope.take(snake(name));
                let rust = self.ty(ty, false)?;
                let mut attrs = vec![format!("rename = {name:?}")];
                if let Some(m) = d20_module(ty) {
                    attrs.push(format!("with = \"{SDK}::json::{m}\""));
                }
                if ty.is_optional() {
                    attrs.push("default".to_owned());
                }
                let _ = writeln!(public_fields, "            {field}: {rust},");
                let _ = writeln!(
                    wire_fields,
                    "            #[serde({})]\n            {field}: {rust},",
                    attrs.join(", ")
                );
                idents.push(field);
            }
            let list = idents.join(", ");
            if idents.is_empty() {
                let _ = writeln!(public, "        {ident},");
                let _ = writeln!(
                    from_wire,
                    "                __Wire::{ident} {{}} => Self::{ident},"
                );
                let _ = writeln!(
                    to_wire,
                    "                Self::{ident} => Ok(__Wire::{ident} {{}}),"
                );
            } else {
                let _ = write!(public, "        {ident} {{\n{public_fields}        }},\n");
                let _ = writeln!(
                    from_wire,
                    "                __Wire::{ident} {{ {list} }} => Self::{ident} {{ {list} }},"
                );
                let _ = writeln!(
                    to_wire,
                    "                Self::{ident} {{ {list} }} => Ok(__Wire::{ident} {{ {list} }}),"
                );
            }
            let _ = write!(
                wire,
                "        #[serde(rename = {code:?})]\n        {ident} {{\n{wire_fields}        }},\n"
            );
        }
        let mut s = String::new();
        let _ = write!(
            s,
            "\n    /// What a call of the app can fail with: one of its own errors (the variants), or\n    \
             /// `Other`: another failure as the SDK reported it (`XcallFailed` with a refusal or a\n    \
             /// timeout, `BadOutput`, `BadArgs`). On the wire every one stays `XcallFailed {{ code, fields }}`.\n    \
             #[derive(Clone, Debug, PartialEq)]\n    pub enum Error {{\n{public}        \
             /// Any other failure, unchanged.\n        Other({SDK}::AppError),\n    }}\n"
        );
        if errors.is_empty() {
            let _ = write!(
                s,
                "\n    impl From<{SDK}::AppError> for Error {{\n        \
                 fn from(e: {SDK}::AppError) -> Self {{\n            Self::Other(e)\n        }}\n    }}\n\n    \
                 impl From<Error> for {SDK}::AppError {{\n        fn from(e: Error) -> Self {{\n            \
                 match e {{\n                Error::Other(e) => e,\n            }}\n        }}\n    }}\n"
            );
        } else {
            let _ = write!(
                s,
                "\n    /// The app's errors as its JSON carries them (`{{ code, fields }}`).\n    \
                 #[derive({SERDE}::Serialize, {SERDE}::Deserialize)]\n    \
                 #[serde(crate = \"{SERDE}\", tag = \"code\", content = \"fields\")]\n    \
                 enum __Wire {{\n{wire}    }}\n\n    \
                 impl Error {{\n        fn from_wire(w: __Wire) -> Self {{\n            match w {{\n{from_wire}            }}\n        }}\n\n        \
                 fn to_wire(self) -> Result<__Wire, {SDK}::AppError> {{\n            match self {{\n{to_wire}                \
                 Self::Other(e) => Err(e),\n            }}\n        }}\n    }}\n\n    \
                 /// A cross-app call's failure, typed when it is one of the app's own errors.\n    \
                 impl From<{SDK}::AppError> for Error {{\n        fn from(e: {SDK}::AppError) -> Self {{\n            \
                 if e.code != \"XcallFailed\" {{\n                return Self::Other(e);\n            }}\n            \
                 let mut wire = e.fields.clone();\n            \
                 if let Some(object) = wire.as_object_mut() {{\n                \
                 if object.get(\"fields\").map_or(true, {VALUE}::is_null) {{\n                    \
                 let _ = object.insert(\"fields\".to_owned(), {VALUE}::Object({JSON}::Map::new()));\n                }}\n            }}\n            \
                 match {JSON}::from_value::<__Wire>(wire) {{\n                Ok(w) => Self::from_wire(w),\n                \
                 Err(_) => Self::Other(e),\n            }}\n        }}\n    }}\n\n    \
                 /// Back to the failure a raw cross-app call gives (`XcallFailed {{ code, fields }}`), so `?`\n    \
                 /// passes it on unchanged.\n    \
                 impl From<Error> for {SDK}::AppError {{\n        fn from(e: Error) -> Self {{\n            \
                 match e.to_wire() {{\n                \
                 Ok(w) => {SDK}::AppError::with_fields(\"XcallFailed\", {JSON}::to_value(&w).unwrap_or_default()),\n                \
                 Err(e) => e,\n            }}\n        }}\n    }}\n"
            );
        }
        let _ = write!(
            s,
            "\n    impl ::core::fmt::Display for Error {{\n        \
             fn fmt(&self, f: &mut ::core::fmt::Formatter<'_>) -> ::core::fmt::Result {{\n            \
             ::core::fmt::Display::fmt(&{SDK}::AppError::from(self.clone()), f)\n        }}\n    }}\n\n    \
             impl ::core::error::Error for Error {{}}\n"
        );
        Ok(s)
    }

    // ── the client ─────────────────────────────────────────────────────────────────────────

    fn client(&mut self) -> EyreResult<String> {
        let mut calls = String::new();
        let mut sends = String::new();
        let methods: Vec<(String, Method)> = self
            .abi
            .methods
            .iter()
            .filter(|(name, m)| callable(self.reference, name, m))
            .map(|(n, m)| (n.clone(), m.clone()))
            .collect();
        let mut scope = Scope::new(&["at", "app_id", "linked", "send"]);
        for (name, m) in &methods {
            let fname = scope.take(snake(name));
            let mut params = Vec::new();
            let mut fields = String::new();
            let mut inits = Vec::new();
            let mut borrows = false;
            let mut param_scope = Scope::new(&["self"]);
            for (pname, pty) in &m.params {
                let ident = param_scope.take(snake(pname));
                let (rust, attrs) = self.arg(pty)?;
                borrows |= rust.contains("'a");
                let mut attrs = attrs;
                attrs.insert(0, format!("rename = {pname:?}"));
                let _ = writeln!(
                    fields,
                    "                #[serde({})]\n                {ident}: {rust},",
                    attrs.join(", ")
                );
                params.push(format!("{ident}: {}", rust.replace("'a ", "")));
                inits.push(ident);
            }
            let lifetime = if borrows { "<'a>" } else { "" };
            let args = format!(
                "            #[derive({SERDE}::Serialize)]\n            #[serde(crate = \"{SERDE}\")]\n            \
                 struct Args{lifetime} {{\n{fields}            }}\n            let args = Args {{ {} }};\n",
                inits.join(", ")
            );
            let sig = std::iter::once("&self".to_owned())
                .chain(params)
                .collect::<Vec<_>>()
                .join(", ");
            let doc: String = m
                .doc
                .as_deref()
                .unwrap_or_default()
                .lines()
                .map(|l| format!("        /// {}\n", l.trim_end()).replace("///  ", "/// "))
                .collect();
            let doc = if doc.is_empty() {
                doc
            } else {
                format!("{doc}        ///\n")
            };
            let view = m.kind == Kind::View;
            let what = if view {
                format!("A view of `{name}` on the linked instance's latest committed state.")
            } else {
                format!(
                    "A call of `{name}`: it runs and commits in the linked app's log before this run\n        \
                     /// continues, and is not rolled back if this run fails afterwards."
                )
            };
            let ret = self.ty(&m.returns, false)?;
            let transport = if view { "xcall_view" } else { "xcall_call" };
            let call = match d20_module(&m.returns) {
                Some(module) => format!(
                    "            #[derive({SERDE}::Deserialize)]\n            #[serde(crate = \"{SERDE}\")]\n            \
                     struct Out(#[serde(with = \"{SDK}::json::{module}\")] {ret});\n            \
                     {SDK}::env::{transport}::<Out, _>(&self.app, {name:?}, &args)\n                \
                     .map(|Out(out)| out)\n                .map_err(Error::from)\n"
                ),
                None => format!(
                    "            {SDK}::env::{transport}::<{ret}, _>(&self.app, {name:?}, &args).map_err(Error::from)\n"
                ),
            };
            let _ = write!(
                calls,
                "\n{doc}        /// {what}\n        pub fn {fname}({sig}) -> Result<{ret}, Error> {{\n{args}{call}        }}\n"
            );
            if m.kind == Kind::Call {
                let _ = write!(
                    sends,
                    "\n        /// `{name}` as an asynchronous message (`env::xcall`): sent only if this run\n        \
                     /// succeeds, delivered at least once and in order; a failure reaches this app's\n        \
                     /// `onXcallFailed`.\n        \
                     pub fn {fname}({sig}) -> {SDK}::Result<()> {{\n{args}            \
                     {SDK}::env::xcall(self.app, {name:?}, &args)\n        }}\n"
                );
            }
        }
        let mut s = String::new();
        let _ = write!(
            s,
            "\n    /// The linked instance. Each method is a synchronous cross-app call: a view reads its\n    \
             /// latest committed state; a call commits in its own log before this run continues and is\n    \
             /// not rolled back if this run fails afterwards (it is not atomic with this run).\n    \
             #[derive(Clone, Debug, PartialEq, Eq)]\n    pub struct Client {{\n        app: String,\n    }}\n\n    \
             impl Client {{\n        \
             /// The instance linked under [`NAME`] (`env::linked`), read now: an owner may attach another\n        \
             /// one later.\n        \
             pub fn linked() -> Option<Self> {{\n            {SDK}::env::linked(NAME).map(|app| Self {{ app }})\n        }}\n\n        \
             /// A client for the instance `app`, which must run a release of [`PACKAGE`] this ABI\n        \
             /// describes.\n        \
             pub fn at(app: impl Into<String>) -> Self {{\n            Self {{ app: app.into() }}\n        }}\n\n        \
             /// The instance's id.\n        \
             pub fn app_id(&self) -> &str {{\n            &self.app\n        }}\n\n        \
             /// The same calls, sent as asynchronous messages.\n        \
             pub fn send(&self) -> Sender<'_> {{\n            Sender {{ app: &self.app }}\n        }}\n\
             {calls}    }}\n\n    \
             /// The app's calls as asynchronous messages ([`Client::send`]).\n    \
             #[derive(Clone, Copy, Debug)]\n    pub struct Sender<'c> {{\n        app: &'c str,\n    }}\n\n    \
             impl Sender<'_> {{{sends}    }}\n"
        );
        Ok(s)
    }

    /// An argument's type in the method's signature (borrowed where it can be) and the
    /// `serde` attributes its JSON needs.
    fn arg(&mut self, ty: &Type) -> EyreResult<(String, Vec<String>)> {
        let mut attrs = Vec::new();
        if let Some(m) = d20_module(ty) {
            attrs.push(format!("serialize_with = \"{SDK}::json::{m}::serialize\""));
        }
        let rust = match ty {
            Type::Unit | Type::Bool | Type::Int(_) | Type::Float(_) | Type::Char => {
                self.ty(ty, false)?
            }
            Type::String => "&'a str".to_owned(),
            Type::Bytes => "&'a [u8]".to_owned(),
            Type::List(inner) => format!("&'a [{}]", self.ty(inner, true)?),
            Type::Option(inner) => {
                attrs.push("skip_serializing_if = \"Option::is_none\"".to_owned());
                match &**inner {
                    Type::Bool | Type::Int(_) | Type::Float(_) | Type::Char => {
                        self.ty(ty, false)?
                    }
                    Type::String => "Option<&'a str>".to_owned(),
                    Type::Bytes => "Option<&'a [u8]>".to_owned(),
                    other => format!("Option<&'a {}>", self.ty(other, true)?),
                }
            }
            other => format!("&'a {}", self.ty(other, false)?),
        };
        Ok((rust, attrs))
    }
}

/// The types a shape holds inline (not behind a list, set or map).
fn inline_types(shape: &Shape) -> Vec<Type> {
    let fields = |fs: &[Field]| fs.iter().map(|f| f.ty.clone()).collect::<Vec<_>>();
    match shape {
        Shape::Record(fs) => fields(fs),
        Shape::Newtype(t) => vec![t.clone()],
        Shape::Tuple(ts) => ts.clone(),
        Shape::Unit => Vec::new(),
        Shape::Enum { variants, .. } => variants
            .iter()
            .flat_map(|v| match &v.data {
                VariantData::Unit => Vec::new(),
                VariantData::Newtype(t) => vec![t.clone()],
                VariantData::Tuple(ts) => ts.clone(),
                VariantData::Record(fs) => fields(fs),
            })
            .collect(),
    }
}

/// `u64`, `i64` or `bytes`: a decimal string or base64url in JSON (D20).
fn is_d20(ty: &Type) -> bool {
    matches!(ty, Type::Int(Int::U64 | Int::I64) | Type::Bytes)
}

/// The `calimero_sdk::json` module that writes `ty` at the top level, when D20 needs one.
fn d20_module(ty: &Type) -> Option<&'static str> {
    Some(match ty {
        Type::Int(Int::U64) => "u64_str",
        Type::Int(Int::I64) => "i64_str",
        Type::Bytes => "bytes_b64url",
        Type::Option(inner) => match &**inner {
            Type::Int(Int::U64) => "opt_u64_str",
            Type::Int(Int::I64) => "opt_i64_str",
            Type::Bytes => "opt_bytes_b64url",
            _ => return None,
        },
        _ => return None,
    })
}

/// `addEvent` → `add_event`, a valid Rust identifier (`type` → `r#type`, `self` → `self_`).
fn snake(name: &str) -> String {
    let mut out = String::new();
    let mut prev_lower = false;
    for c in name.chars() {
        if c.is_ascii_uppercase() {
            if prev_lower {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
            prev_lower = false;
        } else {
            out.push(c);
            prev_lower = c.is_ascii_lowercase() || c.is_ascii_digit();
        }
    }
    let out = sanitize(&out);
    match out.as_str() {
        "_" => "_field".to_owned(),
        "crate" | "self" | "super" | "Self" => format!("{out}_"),
        _ if is_keyword(&out) => format!("r#{out}"),
        _ => out,
    }
}

